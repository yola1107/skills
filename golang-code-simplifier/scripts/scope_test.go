// Run from this directory: go test scope.go scope_test.go
package main

import (
	"bytes"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

func newRepo(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for name, content := range files {
		p := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	for _, args := range [][]string{
		{"init", "-q"},
		{"config", "core.autocrlf", "false"},
		{"add", "-A"},
		{"-c", "user.name=test", "-c", "user.email=test@example.com", "commit", "-q", "-m", "init"},
	} {
		cmd := exec.Command("git", args...)
		cmd.Dir = dir
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, out)
		}
	}
	return dir
}

func runScope(t *testing.T, dir string, args ...string) string {
	t.Helper()
	var out bytes.Buffer
	if err := run(&out, dir, args); err != nil {
		t.Fatal(err)
	}
	return out.String()
}

func assertContains(t *testing.T, out string, wants ...string) {
	t.Helper()
	for _, want := range wants {
		if !strings.Contains(out, want) {
			t.Errorf("output missing %q:\n%s", want, out)
		}
	}
}

func assertNotContains(t *testing.T, out string, unwanted ...string) {
	t.Helper()
	for _, u := range unwanted {
		if strings.Contains(out, u) {
			t.Errorf("output contains %q:\n%s", u, out)
		}
	}
}

const goMod = "module example.com/m\n\ngo 1.22\n"

func TestDeletedFileKeepsPackageInScope(t *testing.T) {
	repo := newRepo(t, map[string]string{
		"go.mod": goMod,
		"a/a.go": "package a\n",
		"a/b.go": "package a\n\nfunc B() {}\n",
	})
	if err := os.Remove(filepath.Join(repo, "a", "b.go")); err != nil {
		t.Fatal(err)
	}

	out := runScope(t, repo)
	assertContains(t, out, "deleted files", "  a/b.go", "packages:\n  ./a\n", "go build ./...", "go vet ./...", "go test ./a")
	assertNotContains(t, out, "no hand-written Go files")
}

func TestDeletedPackageIsReported(t *testing.T) {
	repo := newRepo(t, map[string]string{
		"go.mod": goMod,
		"a/a.go": "package a\n",
		"c/c.go": "package c\n\nimport _ \"example.com/m/a\"\n",
	})
	if err := os.Remove(filepath.Join(repo, "a", "a.go")); err != nil {
		t.Fatal(err)
	}

	out := runScope(t, repo)
	assertContains(t, out, "removed packages", "  ./a", "go build ./...")
	assertNotContains(t, out, "no hand-written Go files", "go test")
}

func TestMovedFileVerifiesBothPackages(t *testing.T) {
	repo := newRepo(t, map[string]string{
		"go.mod": goMod,
		"a/a.go": "package a\n",
		"a/x.go": "package a\n\nfunc X() {}\n",
		"b/b.go": "package b\n",
	})
	cmd := exec.Command("git", "mv", "a/x.go", "b/x.go")
	cmd.Dir = repo
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("git mv: %v\n%s", err, out)
	}

	out := runScope(t, repo)
	assertContains(t, out, "  a/x.go", "  b/x.go", "  ./a\n", "  ./b\n", "go build ./...")
}

func TestExplicitPathsHonorExclusions(t *testing.T) {
	repo := newRepo(t, map[string]string{
		"go.mod":          goMod,
		"a/a.go":          "package a\n",
		"vendor/v/v.go":   "package v\n",
		"testdata/t.go":   "package t\n",
		"a/testdata/y.go": "package y\n",
		"_tools/z.go":     "package z\n",
		"a/gen.go":        "// Code generated by test. DO NOT EDIT.\n\npackage a\n",
	})

	out := runScope(t, repo,
		filepath.Join(repo, "vendor"),
		filepath.Join(repo, "vendor", "v", "v.go"),
		filepath.Join(repo, "testdata", "t.go"),
		"a/testdata",
		"_tools",
		"a",
	)
	assertContains(t, out, "  a/a.go")
	assertNotContains(t, out, "v.go", "t.go", "y.go", "z.go", "gen.go")
}

func writeFile(t *testing.T, repo, name, content string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(repo, filepath.FromSlash(name)), []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestChangedFunctionsAreNamed(t *testing.T) {
	const before = `package a

import "fmt"

// F prints one.
func F() {
	fmt.Println(1)
}

type T struct{}

func (t *T) M() {
	fmt.Println(2)
}

func G() {}
`
	repo := newRepo(t, map[string]string{"go.mod": goMod, "a/a.go": before})
	after := strings.Replace(before, "Println(2)", "Println(3)", 1)
	after = strings.Replace(after, "type T struct{}", "type T struct{ n int }", 1)
	writeFile(t, repo, "a/a.go", after)
	writeFile(t, repo, "a/n.go", "package a\n\nfunc N() {}\n")

	out := runScope(t, repo)
	assertContains(t, out,
		"  a/a.go (changed: T.M; outside functions: lines 10)\n",
		"  a/n.go (new file)\n",
		"gofmt -l a/a.go a/n.go\n")
}

func TestDocCommentChangeNamesFunction(t *testing.T) {
	repo := newRepo(t, map[string]string{
		"go.mod": goMod,
		"a/a.go": "package a\n\n// F does x.\nfunc F() {}\n",
	})
	writeFile(t, repo, "a/a.go", "package a\n\n// F does y.\nfunc F() {}\n")

	out := runScope(t, repo)
	assertContains(t, out, "  a/a.go (changed: F)\n")
}

func TestCRLFReportedOnlyWhenStoredWithCRLF(t *testing.T) {
	repo := newRepo(t, map[string]string{
		"go.mod":     goMod,
		"a/crlf.go":  "package a\r\n\r\nfunc A() {}\r\n",
		"a/lf.go":    "package a\n\nfunc B() {}\n",
		"a/other.go": "package a\n",
	})
	writeFile(t, repo, "a/crlf.go", "package a\r\n\r\nfunc A() { _ = 1 }\r\n")
	writeFile(t, repo, "a/lf.go", "package a\r\n\r\nfunc B() { _ = 1 }\r\n")

	out := runScope(t, repo)
	assertContains(t, out, "convert back after gofmt):\n  a/crlf.go\nverify")
}

func TestExplicitSkippedPathsOnly(t *testing.T) {
	repo := newRepo(t, map[string]string{
		"go.mod":        goMod,
		"vendor/v/v.go": "package v\n",
	})

	out := runScope(t, repo, "vendor")
	assertContains(t, out, "no hand-written Go files in scope")
}
